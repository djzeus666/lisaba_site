/** Structured provider section content for CMS seed (mirrors providerBodies.tsx). */

export type SeedBlock =
  | { blockType: "heading"; text: string }
  | { blockType: "paragraph"; text: string }
  | { blockType: "list"; items: { text: string }[] }
  | { blockType: "docs"; items: { label: string; href?: string }[] }
  | {
      blockType: "card";
      title?: string;
      paragraphs?: { text: string }[];
      lists?: { heading?: string; items: { text: string }[] }[];
      docs?: { label: string; href?: string }[];
    };

const p = (text: string): SeedBlock => ({ blockType: "paragraph", text });
const h = (text: string): SeedBlock => ({ blockType: "heading", text });
const ul = (...items: string[]): SeedBlock => ({
  blockType: "list",
  items: items.map((text) => ({ text })),
});
const docs = (...items: { label: string; href: string }[]): SeedBlock => ({
  blockType: "docs",
  items,
});
const card = (
  title: string | undefined,
  data: {
    paragraphs?: string[];
    lists?: { heading?: string; items: string[] }[];
    docs?: { label: string; href: string }[];
  },
): SeedBlock => ({
  blockType: "card",
  title,
  paragraphs: data.paragraphs?.map((text) => ({ text })),
  lists: data.lists?.map((l) => ({
    heading: l.heading,
    items: l.items.map((text) => ({ text })),
  })),
  docs: data.docs,
});

